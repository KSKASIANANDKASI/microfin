-- Identity proofs move off the customer row into their own table, so a customer can hold
-- several (one per ID type, e.g. Aadhaar and PAN).

create table customer_id_proofs (
    id             bigint generated by default as identity primary key,
    customer_id    bigint       not null references customers (id) on delete cascade,
    id_type        varchar(20)  not null,
    -- AES-GCM ciphertext; see IdNumberCipher.
    id_number      varchar(255) not null,
    front_file_id  uuid references stored_files (id),
    back_file_id   uuid references stored_files (id),
    created_by     bigint references users (id),
    created_at     timestamp with time zone not null,
    updated_at     timestamp with time zone not null,
    constraint uq_customer_id_proofs_type unique (customer_id, id_type),
    constraint ck_customer_id_proofs_type check (id_type in ('AADHAAR', 'PAN', 'VOTER_ID', 'DRIVING_LICENSE', 'PASSPORT'))
);
create index idx_customer_id_proofs_customer on customer_id_proofs (customer_id);

-- Carry existing proofs across. The ciphertext is not bound to its row, so it copies as is.
insert into customer_id_proofs (customer_id, id_type, id_number, front_file_id, back_file_id, created_by, created_at, updated_at)
select id, id_type, id_number, proof_front_id, proof_back_id, created_by, updated_at, updated_at
from customers
where id_type is not null and id_number is not null;

alter table customers drop constraint ck_customers_id_type;
alter table customers drop column id_type;
alter table customers drop column id_number;
alter table customers drop column proof_front_id;
alter table customers drop column proof_back_id;
