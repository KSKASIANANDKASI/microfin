-- Money convention: every amount column is BIGINT whole rupees. These branches collect at the
-- doorstep and do not handle paise; nothing monetary is ever stored as a float.
-- Rows are addressed publicly by their human code (L04, C-0007, APP-3104, LN-20418), which is
-- unique within a company. The bigint ids never leave the server.

create table companies (
    id           bigint generated by default as identity primary key,
    name         varchar(120) not null,
    office_lat   numeric(9, 6),
    office_lng   numeric(9, 6),
    daily_target bigint       not null default 0,
    created_at   timestamp with time zone not null
);

create table users (
    id                  bigint generated by default as identity primary key,
    company_id          bigint       not null references companies (id),
    full_name           varchar(120) not null,
    email               varchar(254) not null,
    phone               varchar(15)  not null,
    password_hash       varchar(100) not null,
    role                varchar(20)  not null,
    status              varchar(12)  not null,
    -- Bumped on every password change; tokens carrying an older value are refused.
    token_version       int          not null default 0,
    last_login_at       timestamp with time zone,
    created_at          timestamp with time zone not null,
    constraint uq_users_email unique (email),
    constraint ck_users_role check (role in ('ADMIN', 'MANAGER', 'LOAN_OFFICER')),
    constraint ck_users_status check (status in ('ACTIVE', 'SUSPENDED'))
);
create index idx_users_company on users (company_id, role);

create table password_reset_tokens (
    id         bigint generated by default as identity primary key,
    user_id    bigint      not null references users (id) on delete cascade,
    token_hash varchar(64) not null unique,
    expires_at timestamp with time zone not null,
    used_at    timestamp with time zone,
    created_at timestamp with time zone not null
);

-- Last number handed out per company for each kind of code.
create table code_counters (
    company_id bigint      not null references companies (id),
    name       varchar(20) not null,
    last_value bigint      not null,
    primary key (company_id, name)
);

create table lines (
    id         bigint generated by default as identity primary key,
    company_id bigint       not null references companies (id),
    code       varchar(12)  not null,
    name       varchar(120) not null,
    officer_id bigint references users (id),
    frequency  varchar(20)  not null,
    schedule   varchar(12),
    created_at timestamp with time zone not null,
    constraint uq_lines_code unique (company_id, code),
    constraint ck_lines_frequency check (frequency in ('DAILY', 'WEEKLY', 'MONTHLY', 'MONTHLY_INTEREST'))
);

create table stored_files (
    id            uuid primary key,
    company_id    bigint       not null references companies (id),
    original_name varchar(255) not null,
    content_type  varchar(100) not null,
    size_bytes    bigint       not null,
    storage_path  varchar(255) not null,
    uploaded_by   bigint references users (id),
    created_at    timestamp with time zone not null
);

create table customers (
    id               bigint generated by default as identity primary key,
    company_id       bigint       not null references companies (id),
    code             varchar(12)  not null,
    line_id          bigint       not null references lines (id),
    name             varchar(120) not null,
    phone            varchar(10)  not null,
    alt_phone        varchar(10),
    parent_name      varchar(120) not null,
    address          varchar(300) not null,
    requested_amount bigint       not null,
    status           varchar(10)  not null,
    geo_lat          numeric(9, 6),
    geo_lng          numeric(9, 6),
    geo_accuracy     numeric(8, 2),
    geo_captured_at  timestamp with time zone,
    id_type          varchar(20),
    -- AES-GCM ciphertext; see IdNumberCipher.
    id_number        varchar(255),
    proof_front_id   uuid references stored_files (id),
    proof_back_id    uuid references stored_files (id),
    created_by       bigint references users (id),
    created_at       timestamp with time zone not null,
    updated_at       timestamp with time zone not null,
    constraint uq_customers_code unique (company_id, code),
    constraint uq_customers_phone unique (company_id, phone),
    constraint ck_customers_status check (status in ('PENDING', 'APPROVED', 'ACTIVE')),
    constraint ck_customers_id_type check (id_type in ('AADHAAR', 'PAN', 'VOTER_ID', 'DRIVING_LICENSE', 'PASSPORT'))
);
create index idx_customers_line on customers (line_id);

create table loans (
    id             bigint generated by default as identity primary key,
    company_id     bigint        not null references companies (id),
    loan_no        varchar(16)   not null,
    customer_id    bigint        not null references customers (id),
    line_id        bigint        not null references lines (id),
    type           varchar(4)    not null,
    principal      bigint        not null,
    annual_rate_pct numeric(6, 3) not null,
    months         int           not null,
    fee            bigint        not null,
    emi            bigint        not null,
    total_interest bigint        not null,
    total_payable  bigint        not null,
    net_disbursal  bigint        not null,
    disbursed_on   date          not null,
    disbursed_by   bigint references users (id),
    status         varchar(8)    not null,
    closed_on      date,
    created_at     timestamp with time zone not null,
    constraint uq_loans_no unique (company_id, loan_no),
    constraint ck_loans_type check (type in ('POST', 'PRE')),
    constraint ck_loans_status check (status in ('ACTIVE', 'CLOSED'))
);
create index idx_loans_customer on loans (customer_id);
create index idx_loans_line_status on loans (line_id, status);

create table loan_applications (
    id              bigint generated by default as identity primary key,
    company_id      bigint        not null references companies (id),
    code            varchar(16)   not null,
    customer_id     bigint        not null references customers (id),
    line_id         bigint        not null references lines (id),
    type            varchar(4)    not null,
    principal       bigint        not null,
    annual_rate_pct numeric(6, 3) not null,
    months          int           not null,
    fee             bigint        not null,
    emi             bigint        not null,
    disburse_on     date          not null,
    submitted_on    date          not null,
    submitted_by_id bigint references users (id),
    -- The line's officer when it was submitted, kept as text so later reassignment does not rewrite it.
    submitted_by    varchar(120)  not null,
    status          varchar(10)   not null,
    note            varchar(500),
    decided_on      date,
    decided_by_id   bigint references users (id),
    loan_id         bigint references loans (id),
    created_at      timestamp with time zone not null,
    constraint uq_applications_code unique (company_id, code),
    constraint ck_applications_type check (type in ('POST', 'PRE')),
    constraint ck_applications_status check (status in ('PENDING', 'APPROVED', 'REJECTED', 'DISBURSED'))
);
create index idx_applications_status on loan_applications (company_id, status);
create index idx_applications_customer on loan_applications (customer_id);

-- One row per installment, written once at disbursal. paid_on is set when it is receipted.
create table loan_installments (
    id            bigint generated by default as identity primary key,
    loan_id       bigint not null references loans (id) on delete cascade,
    seq           int    not null,
    due_on        date   not null,
    amount        bigint not null,
    balance_after bigint not null,
    paid_on       date,
    constraint uq_installments_seq unique (loan_id, seq)
);
create index idx_installments_due on loan_installments (due_on, paid_on);

create table payments (
    id              bigint generated by default as identity primary key,
    company_id      bigint      not null references companies (id),
    loan_id         bigint      not null references loans (id),
    installment_id  bigint      not null references loan_installments (id),
    seq             int         not null,
    receipt_no      varchar(24) not null,
    amount          bigint      not null,
    paid_on         date        not null,
    days_late       int         not null,
    mode            varchar(8)  not null,
    posted_at       timestamp with time zone not null,
    geo_lat         numeric(9, 6),
    geo_lng         numeric(9, 6),
    geo_accuracy    numeric(8, 2),
    collected_by_id bigint references users (id),
    -- Idempotency key minted on the device, so an offline receipt posts exactly once.
    client_op_id    varchar(64),
    constraint uq_payments_installment unique (installment_id),
    constraint uq_payments_receipt unique (company_id, receipt_no),
    constraint uq_payments_client_op unique (company_id, client_op_id),
    constraint ck_payments_mode check (mode in ('CASH', 'UPI'))
);
create index idx_payments_paid_on on payments (company_id, paid_on);
create index idx_payments_loan on payments (loan_id);

create table audit_logs (
    id         bigint generated by default as identity primary key,
    company_id bigint      not null references companies (id),
    actor_id   bigint references users (id),
    action     varchar(40) not null,
    entity     varchar(30) not null,
    entity_code varchar(40),
    detail     varchar(1000),
    created_at timestamp with time zone not null
);
create index idx_audit_entity on audit_logs (company_id, entity, entity_code);
